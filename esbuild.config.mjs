import esbuild from 'esbuild';
import process from 'node:process';
import fs from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Yandex Disk Sync Plugin
Cross-Platform (Windows & Android) - Zero Node.js fs dependencies
*/
`;

const prod = (process.argv[2] === 'production');

/**
 * esbuild plugin that traps and blocks any accidental Node.js built-in module imports
 * to enforce 100% Android WebView compatibility at compile time.
 */
const disallowNodeBuiltinsPlugin = {
  name: 'disallow-node-builtins',
  setup(build) {
    const nodeBuiltinRegex = /^(node:)?(fs|path|os|crypto|child_process|net|http|https|stream|cluster|dgram|dns|readline|repl|tls|tty|v8|vm|zlib)(\/.*)?$/;
    build.onResolve({ filter: nodeBuiltinRegex }, (args) => {
      return {
        errors: [{
          text: `Forbidden Node.js built-in module import "${args.path}" in cross-platform plugin! Obsidian Mobile (Android/iOS) has no Node.js runtime. Use Obsidian Vault API (app.vault) and Web Standard APIs (crypto.subtle, TextEncoder, etc.) instead.`,
        }],
      };
    });
  },
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['src/main.ts'],
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
  minify: prod,
  // Only externalize Obsidian and standard CodeMirror dependencies provided by Obsidian runtime.
  // DO NOT include builtinModules or electron!
  external: [
    'obsidian',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
  ],
  plugins: [
    disallowNodeBuiltinsPlugin,
  ],
});

if (prod) {
  await context.rebuild();

  // Post-build verification: Guarantee zero Node.js desktop dependencies in generated main.js
  const bundleContent = fs.readFileSync('main.js', 'utf8');
  const forbiddenPatterns = [
    /require\(["']fs["']\)/,
    /require\(["']node:fs["']\)/,
    /require\(["']path["']\)/,
    /require\(["']node:path["']\)/,
    /require\(["']os["']\)/,
    /require\(["']electron["']\)/,
    /require\(["']child_process["']\)/,
  ];

  for (const pattern of forbiddenPatterns) {
    if (pattern.test(bundleContent)) {
      console.error(`FATAL: Forbidden desktop-only import found in main.js: ${pattern}`);
      process.exit(1);
    }
  }

  console.log('✓ Build successful: main.js generated with zero Node.js desktop dependencies.');
  process.exit(0);
} else {
  await context.watch();
}
